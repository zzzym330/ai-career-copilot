function createJd(
  title: string,
  responsibilities: string[],
  requirements: string[],
) {
  return `岗位名称：${title}

岗位职责：
${responsibilities.map((item, index) => `${index + 1}. ${item}`).join("\n")}

岗位要求：
${requirements.map((item, index) => `${index + 1}. ${item}`).join("\n")}`;
}

